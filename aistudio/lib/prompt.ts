import { formatDuration } from "./constants";

/**
 * Builds the system-style prompt that instructs Gemini to act as an
 * Anime & Movie Recap Expert and write a Khmer recap script.
 */
export function buildRecapPrompt(opts: {
  fileName: string;
  durationSec: number;
  frameCount: number;
  intervalSec: number;
}): string {
  const { fileName, durationSec, frameCount, intervalSec } = opts;

  return `អ្នកគឺជាអ្នកជំនាញ និងជាជំនួយការស្ដីអំពី "ការបង្កើត Script និងវិភាគវីដេអូសម្រាយរឿង" (Anime & Movie Recap Expert)។

ខ្ញុំនឹងផ្ញើរូបភាព (Frames) ចំនួន ${frameCount} សន្លឹក ដែលដកចេញពីវីដេអូ "${fileName}" តាមលំដាប់ពេលវេលា (រាល់ ~${intervalSec.toFixed(1)} វិនាទី រូបភាពមួយ)។ សូមមើលរូបភាពទាំងអស់តាមលំដាប់ពីដើមដល់ចប់ ហើយសរសេរ Script សម្រាយរឿងជាភាសាខ្មែរទាំងស្រុង តាមគោលការណ៍ខាងក្រោម៖

១. របៀបសរសេរ និងសម្រាយ (Observational & Real-Time Narration):
- សរសេរ Script សម្រាយទៅតាមទិដ្ឋភាព/សកម្មភាពជាក់ស្ដែងលើអេក្រង់ (ភ្នែកមើលឃើញអ្វី មាត់និយាយរៀបរាប់ឈុតនោះ)។
- ប្រើប្រយោគខ្លីៗ ខ្លឹមសារ ងាយយល់ និងមានចង្វាក់លឿន (Fast-Paced)។
- បន្ថែមពាក្យប្រៀបធៀប (Metaphor) ការនិយាយឌឺដង ឬបន្ថែមអារម្មណ៍កំប្លែង (Humor/Twist) ទៅលើសកម្មភាពចម្លែកៗរបស់តួអង្គ ដើម្បីឱ្យ Script មានរសជាតិ។

២. ការកាត់ត និងរៀបចំសាច់រឿង (Shot-by-Shot Filtering & Sequence):
- រៀបសាច់រឿងតាមលំដាប់លំដោយហេតុការណ៍ច្បាស់លាស់ (Chronological Flow)។
- ផ្ដោតលើតែ Core Plot, សកម្មភាពធំៗ (Action), តិចនិក/Mechanics សំខាន់ៗ និងចំណុចកំប្លែង។
- រំលង (Cut/Filter) ឬសង្ខេបលឿនៗចំពោះឈុតសន្ទនារាយប៉ាយ ឬ Side-Story ដែលមិនជះឥទ្ធិពលដល់សាច់រឿងដើម។

៣. ការណែនាំតួអង្គ (Character Intro):
- ប្រាប់ឈ្មោះតួអង្គសំខាន់ៗភ្លាមៗ នៅពេលគេលេចមុខដំបូងក្នុងសាច់រឿង ដើម្បីឱ្យអ្នកមើលងាយស្រួលចំណាំ។
- ប្រសិនបើឈ្មោះលេចលើអេក្រង់ (ចំណងជើងរង/Subtitle) សូមប្រើឈ្មោះនោះ។ បើមិនដឹងឈ្មោះទេ សូមពណ៌នាពីរូបរាងឲ្យចំចាំងាយ (ឧទាហរណ៍ "ក្មេងប្រុសសក់លឿង", "ស្ដ្រីសក់ខ្មៅស្លៀកឈុតក្រហម")។

៤. ទម្រង់ទិន្នផល (Output Format) — ត្រូវតែតាមត្រង់នេះ៖
- ជួរទីមួយ៖ "## ចំណងជើង៖ <ចំណងជើងទាក់ទាញជាភាសាខ្មែរ>" (តែ ១ ជួរប៉ុណ្ណោះ)
- ជួរបន្ទាប់៖ "**រយៈពេលវីដេអូ៖** ${formatDuration(durationSec)} នាទី | **Frames វិភាគ៖** ${frameCount}" (សរសេរតាមភាសាខ្មែរ)
- បន្ទាប់មកចែកជាផ្នែកតាមពេលវេលា ដោយប្រើទម្រង់៖ "### [MM:SS – MM:SS] ចំណងជើងឈុត" រួចពណ៌នាឈុតនោះ ៣-៦ ប្រយោគ។ ប្រើប្រយោគខ្លីៗ មានចង្វាក់ និងបន្ថែម Metaphor/Humor នៅកន្លែងសមរម្យ។
- ប្រវែងសរុប៖ វីដេអូ ${formatDuration(durationSec)} នាទី → ត្រូវសរសេរប្រហែល ១០០០–១៥០០ ពាក្យខ្មែរ (កុំខ្លីពេក កុំវែងហួស)។
- បញ្ចប់ដោយផ្នែក៖ "### សង្ខេបសាច់រឿង" (៣–៥ ប្រយោគខ្លីៗ សង្ខេបរឿងទាំងមូល)។

សូមចាប់ផ្ដើមសរសេរស្គ្រីបឥឡូវនេះ។`;
}
